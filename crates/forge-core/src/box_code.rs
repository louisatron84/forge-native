//! Plain standard-library Python and test requests for Connect boxes,
//! replacing `src/shared/boxCode.ts`. Generated code reads secrets from env.
use crate::boxes::{env_name, function_name_for, py_name, ApiBox, ApiRequest, BoxAuth};
use std::collections::{BTreeMap, HashSet};
fn placeholders() -> &'static regex::Regex {
    static PATTERN: std::sync::LazyLock<regex::Regex> =
        std::sync::LazyLock::new(|| regex::Regex::new(r"\{([^{}]+)\}").expect("fixed placeholder regex"));
    &PATTERN
}
pub fn url_args(url: &str) -> Vec<String> {
    let mut out = Vec::new();
    for capture in placeholders().captures_iter(url) {
        let name = py_name(&capture[1]);
        if !out.contains(&name) {
            out.push(name);
        }
    }
    out
}
pub fn auth_env(api: &ApiBox) -> Vec<String> {
    let fallback = |value: &String, suffix| if value.is_empty() { env_name(&api.name, suffix) } else { value.clone() };
    match &api.auth {
        BoxAuth::None => Vec::new(),
        BoxAuth::Header { env, .. } | BoxAuth::Query { env, .. } => vec![fallback(env, "KEY")],
        BoxAuth::Bearer { env } => vec![fallback(env, "TOKEN")],
        BoxAuth::Basic { user_env, pass_env } => vec![fallback(user_env, "USER"), fallback(pass_env, "PASSWORD")],
    }
}
pub fn request_functions(api: &ApiBox) -> BTreeMap<String, String> {
    let mut out = BTreeMap::new();
    let mut used = HashSet::new();
    for request in &api.requests {
        let base = function_name_for(api, request);
        let mut name = base.clone();
        let mut n = 2;
        while used.contains(&name) {
            name = format!("{base}_{n}");
            n += 1;
        }
        used.insert(name.clone());
        out.insert(request.id.clone(), name);
    }
    out
}
pub(crate) fn s(text: &str) -> String {
    let json = serde_json::to_string(text).unwrap_or_default();
    let mut out = String::new();
    for ch in json.chars() {
        if ch as u32 >= 0x80 {
            let mut buf = [0; 2];
            for unit in ch.encode_utf16(&mut buf) {
                out.push_str(&format!("\\u{unit:04x}"));
            }
        } else {
            out.push(ch);
        }
    }
    out
}
fn literal(value: &serde_json::Value) -> String {
    match value {
        serde_json::Value::Null => "None".into(),
        serde_json::Value::Bool(true) => "True".into(),
        serde_json::Value::Bool(false) => "False".into(),
        serde_json::Value::String(text) => s(text),
        serde_json::Value::Array(a) => format!("[{}]", a.iter().map(literal).collect::<Vec<_>>().join(", ")),
        serde_json::Value::Object(o) => {
            format!("{{{}}}", o.iter().map(|(k, v)| format!("{}: {}", s(k), literal(v))).collect::<Vec<_>>().join(", "))
        }
        serde_json::Value::Number(n) => {
            n.as_f64().filter(|n| n.fract() == 0.0).map(|n| format!("{n:.0}")).unwrap_or_else(|| n.to_string())
        }
    }
}
fn doc_text(text: &str) -> String {
    let mut out = String::new();
    let mut whitespace = false;
    for c in text.chars() {
        if c == '"' || c == '\\' {
            continue;
        }
        if c.is_whitespace() {
            if !whitespace {
                out.push(' ');
            }
            whitespace = true;
        } else {
            out.push(c);
            whitespace = false;
        }
    }
    out
}
fn has_body(req: &ApiRequest) -> bool {
    matches!(req.method.as_str(), "POST" | "PUT" | "PATCH") && !req.body.trim().is_empty()
}
fn append(lines: &mut Vec<String>, text: &str) {
    lines.extend(text.split('\n').map(str::to_owned));
}
fn helper(api: &ApiBox, p: &str) -> Vec<String> {
    let mut out = Vec::new();
    let base = api.base_url.trim();
    let base_const = format!("{}_BASE_URL", p.trim_start_matches('_').to_uppercase());
    if !base.is_empty() {
        out.extend([format!("{base_const} = {}", s(base)), String::new(), String::new()]);
    }
    out.extend([
        format!("def _{p}_request(method, url, params=None, headers=None, body=None):"),
        format!(
            "    \"\"\"Call the {} API and return the JSON it sends back (generated by Forge).\"\"\"",
            doc_text(&api.name)
        ),
    ]);
    append(
        &mut out,
        "    headers = {\"Accept\": \"application/json\", **(headers or {})}\n    params = dict(params or {})",
    );
    let names = auth_env(api);
    let mut secret = |variable: &str, name: &str| {
        out.extend([
            format!("    {variable} = os.environ.get({})", s(name)),
            format!("    if not {variable}:"),
            format!("        raise RuntimeError({})", s(&format!("{name} is not set: add it to .env"))),
        ]);
    };
    match &api.auth {
        BoxAuth::None => {}
        BoxAuth::Header { .. } | BoxAuth::Query { .. } => secret("key", &names[0]),
        BoxAuth::Bearer { .. } => secret("token", &names[0]),
        BoxAuth::Basic { .. } => {
            secret("user", &names[0]);
            secret("password", &names[1]);
        }
    }
    match &api.auth{BoxAuth::Header{name,..}=>out.push(format!("    headers[{}] = key",s(if name.trim().is_empty(){"X-Api-Key"}else{name.trim()}))),BoxAuth::Query{name,..}=>out.push(format!("    params[{}] = key",s(if name.trim().is_empty(){"api_key"}else{name.trim()}))),BoxAuth::Bearer{..}=>out.push("    headers[\"Authorization\"] = \"Bearer \" + token".into()),BoxAuth::Basic{..}=>out.push("    headers[\"Authorization\"] = \"Basic \" + base64.b64encode((user + \":\" + password).encode(\"utf-8\")).decode(\"ascii\")".into()),BoxAuth::None=>{}}
    if !base.is_empty() {
        out.extend([
            "    if not url.startswith((\"http://\", \"https://\")):".into(),
            format!("        url = {base_const}.rstrip(\"/\") + \"/\" + url.lstrip(\"/\")"),
        ]);
    }
    append(&mut out,"    if params:\n        url += (\"&\" if \"?\" in url else \"?\") + urllib.parse.urlencode(params)\n    data = None\n    if body is not None:\n        data = json.dumps(body).encode(\"utf-8\")\n        headers[\"Content-Type\"] = \"application/json\"\n    request = urllib.request.Request(url, data=data, headers=headers, method=method)\n    with urllib.request.urlopen(request, timeout=30) as response:\n        return json.loads(response.read().decode(\"utf-8\"))\n\n");
    out.push(format!("def _{p}_cell(record, key):"));
    append(&mut out,"    \"\"\"One CSV cell: a field of a record (nested fields are joined with dots).\"\"\"\n    value = record\n    for part in key.split(\".\"):\n        value = value.get(part) if isinstance(value, dict) else None\n    if value is None:\n        return \"\"\n    if isinstance(value, (bool, list, dict)):\n        return json.dumps(value)\n    return str(value)");
    out
}
fn function_code(api: &ApiBox, req: &ApiRequest, name: &str, p: &str) -> Vec<String> {
    let args = url_args(&req.url);
    let mut params = args.clone();
    params.extend(
        req.query
            .iter()
            .filter(|q| !q.key.trim().is_empty() && q.arg)
            .map(|q| format!("{}={}", py_name(&q.key), s(&q.value))),
    );
    let output = if req.output.is_empty() { format!("{name}.csv") } else { req.output.clone() };
    params.push(format!("output_path={}", s(&output)));
    let mut out = vec![
        format!("def {name}({}):", params.join(", ")),
        format!(
            "    \"\"\"{} {} → {} (generated by Forge).\"\"\"",
            req.method,
            doc_text(if req.url.is_empty() { "(no URL yet)" } else { &req.url }),
            doc_text(&output)
        ),
    ];
    let mut call = vec![s(&req.method)];
    if !args.is_empty() {
        let template =
            placeholders().replace_all(req.url.trim(), |c: &regex::Captures| format!("{{{}}}", py_name(&c[1])));
        out.push(format!(
            "    url = {}.format({})",
            s(&template),
            args.iter().map(|a| format!("{a}=urllib.parse.quote(str({a}), safe=\"\")")).collect::<Vec<_>>().join(", ")
        ));
        call.push("url".into());
    } else {
        call.push(s(req.url.trim()));
    }
    let query: Vec<_> = req.query.iter().filter(|q| !q.key.trim().is_empty()).collect();
    if !query.is_empty() {
        out.push(format!(
            "    params = {{{}}}",
            query
                .iter()
                .map(|q| format!("{}: {}", s(q.key.trim()), if q.arg { py_name(&q.key) } else { s(&q.value) }))
                .collect::<Vec<_>>()
                .join(", ")
        ));
        call.push("params=params".into());
    }
    let headers: Vec<_> = req.headers.iter().filter(|h| !h.key.trim().is_empty()).collect();
    if !headers.is_empty() {
        out.push(format!(
            "    headers = {{{}}}",
            headers.iter().map(|h| format!("{}: {}", s(h.key.trim()), s(&h.value))).collect::<Vec<_>>().join(", ")
        ));
        call.push("headers=headers".into());
    }
    if has_body(req) {
        out.push(match serde_json::from_str::<serde_json::Value>(&req.body) {
            Ok(v) => format!("    body = {}", literal(&v)),
            Err(_) => "    body = None  # the body in Forge isn't valid JSON yet".into(),
        });
        call.push("body=body".into());
    }
    out.push(format!("    data = _{p}_request({})", call.join(", ")));
    out.push(match &req.records_path {
        None => "    records = data if isinstance(data, list) else [data]".into(),
        Some(path) => format!("    records = data{}", path.iter().map(|k| format!("[{}]", s(k))).collect::<String>()),
    });
    out.push("    records = [r if isinstance(r, dict) else {\"value\": r} for r in records]".into());
    if !req.ticked.is_empty() {
        out.push(format!("    fields = [{}]", req.ticked.iter().map(|k| s(k)).collect::<Vec<_>>().join(", ")));
    } else {
        append(&mut out,"    fields = []\n    for record in records:\n        for key in record:\n            if key not in fields:\n                fields.append(key)");
    }
    out.push(format!("    rows = [{{key: _{p}_cell(record, key) for key in fields}} for record in records]"));
    append(&mut out,"    with open(output_path, \"w\", newline=\"\", encoding=\"utf-8\") as f:\n        writer = csv.DictWriter(f, fieldnames=fields)\n        writer.writeheader()\n        writer.writerows(rows)\n    return rows");
    let _ = api;
    out
}
pub fn generate_block(api: &ApiBox, main: bool) -> String {
    let p = py_name(&api.name);
    let functions = request_functions(api);
    let mut out = vec![format!("# forge:box {} (generated, edit in Forge or here)", api.id)];
    if matches!(api.auth, BoxAuth::Basic { .. }) {
        out.push("import base64".into());
    }
    for name in ["csv", "json", "os", "urllib.parse", "urllib.request"] {
        out.push(format!("import {name}"));
    }
    out.extend([String::new(), String::new()]);
    out.extend(helper(api, &p));
    for req in &api.requests {
        out.extend([String::new(), String::new()]);
        if let Some(name) = functions.get(&req.id) {
            out.extend(function_code(api, req, name, &p));
        }
    }
    if main {
        out.extend([String::new(), String::new(), "if __name__ == \"__main__\":".into()]);
        for req in &api.requests {
            if let Some(name) = functions.get(&req.id) {
                out.push(format!(
                    "    {name}({})",
                    url_args(&req.url)
                        .iter()
                        .map(|a| s(req.test_args.get(a).map(String::as_str).unwrap_or("")))
                        .collect::<Vec<_>>()
                        .join(", ")
                ));
            }
        }
    }
    out.push(format!("# forge:end {}", api.id));
    out.join("\n") + "\n"
}
pub fn block_hash(text: &str) -> String {
    let hash =
        text.replace("\r\n", "\n").encode_utf16().fold(0x811c9dc5_u32, |h, c| (h ^ c as u32).wrapping_mul(0x01000193));
    format!("{hash:08x}")
}
#[derive(Clone, Debug, PartialEq)]
pub struct BuiltRequest {
    pub method: String,
    pub url: String,
    pub headers: BTreeMap<String, String>,
    pub body: Option<String>,
}
fn encode(text: &str, form: bool) -> String {
    let mut out = String::new();
    for b in text.bytes() {
        if b.is_ascii_alphanumeric() || b"-._*".contains(&b) || (!form && b"!~'()".contains(&b)) {
            out.push(b as char);
        } else if form && b == b' ' {
            out.push('+');
        } else {
            out.push_str(&format!("%{b:02X}"));
        }
    }
    out
}
pub fn build_request(api: &ApiBox, req: &ApiRequest, env: &BTreeMap<String, String>) -> Result<BuiltRequest, String> {
    use base64::Engine;
    let mut missing = None;
    let mut url = placeholders()
        .replace_all(req.url.trim(), |c: &regex::Captures| {
            let key = py_name(&c[1]);
            let v = req.test_args.get(&key).map(String::as_str).unwrap_or("");
            if v.is_empty() && missing.is_none() {
                missing = Some(key);
            }
            encode(v, false)
        })
        .into_owned();
    if let Some(key) = missing {
        return Err(format!("Fill in a test value for {key}."));
    }
    let http = |url: &str| {
        url.get(..7).is_some_and(|s| s.eq_ignore_ascii_case("http://"))
            || url.get(..8).is_some_and(|s| s.eq_ignore_ascii_case("https://"))
    };
    if !http(&url) && !api.base_url.trim().is_empty() {
        url = format!("{}/{}", api.base_url.trim().trim_end_matches('/'), url.trim_start_matches('/'));
    }
    let host = url.split_once("://").map(|(_, s)| s);
    if !http(&url) || host.is_none_or(|h| h.is_empty() || h.starts_with('/')) {
        return Err("The URL must start with http:// or https:// (or set a base URL).".into());
    }
    let mut params: Vec<_> = req
        .query
        .iter()
        .filter(|q| !q.key.trim().is_empty())
        .map(|q| (q.key.trim().to_owned(), q.value.clone()))
        .collect();
    let mut headers = BTreeMap::from([("Accept".into(), "application/json".into())]);
    for h in &req.headers {
        if !h.key.trim().is_empty() {
            headers.insert(h.key.trim().into(), h.value.clone());
        }
    }
    let body = if has_body(req) {
        if serde_json::from_str::<serde_json::Value>(&req.body).is_err() {
            return Err("The body isn't valid JSON.".into());
        }
        headers.insert("Content-Type".into(), "application/json".into());
        Some(req.body.clone())
    } else {
        None
    };
    let mut secrets = Vec::new();
    for name in auth_env(api) {
        secrets.push(
            env.get(&name).filter(|v| !v.is_empty()).ok_or_else(|| format!("{name} is not set: add it to .env"))?,
        );
    }
    match &api.auth {
        BoxAuth::None => {}
        BoxAuth::Header { name, .. } => {
            headers.insert(if name.trim().is_empty() { "X-Api-Key" } else { name.trim() }.into(), secrets[0].clone());
        }
        BoxAuth::Query { name, .. } => {
            params.push((if name.trim().is_empty() { "api_key" } else { name.trim() }.into(), secrets[0].clone()))
        }
        BoxAuth::Bearer { .. } => {
            headers.insert("Authorization".into(), format!("Bearer {}", secrets[0]));
        }
        BoxAuth::Basic { .. } => {
            headers.insert(
                "Authorization".into(),
                format!(
                    "Basic {}",
                    base64::engine::general_purpose::STANDARD.encode(format!("{}:{}", secrets[0], secrets[1]))
                ),
            );
        }
    }
    if !params.is_empty() {
        url.push(if url.contains('?') { '&' } else { '?' });
        url.push_str(
            &params
                .iter()
                .map(|(k, v)| format!("{}={}", encode(k, true), encode(v, true)))
                .collect::<Vec<_>>()
                .join("&"),
        );
    }
    Ok(BuiltRequest { method: req.method.clone(), url, headers, body })
}
#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn generated_blocks_match_electron_for_auth_requests_csv_and_main() {
        let cases: Vec<serde_json::Value> =
            serde_json::from_str(include_str!("../tests/fixtures/api_code.json")).unwrap();
        for (index, case) in cases.iter().enumerate() {
            let api = serde_json::from_value(case["box"].clone()).unwrap();
            assert_eq!(
                generate_block(&api, case["main"].as_bool().unwrap()),
                case["expected"].as_str().unwrap(),
                "case {index}"
            );
        }
    }
    #[test]
    fn placeholders_become_python_names_in_order() {
        assert_eq!(url_args("/users/{user name}/repos/{Repo}"), ["user_name", "repo"]);
        assert!(url_args("/plain").is_empty());
    }
    #[test]
    fn test_call_joins_base_fills_placeholders_encodes_query_and_auth() {
        let cases: Vec<serde_json::Value> =
            serde_json::from_str(include_str!("../tests/fixtures/api_code.json")).unwrap();
        let api: ApiBox = serde_json::from_value(cases[0]["box"].clone()).unwrap();
        let env = BTreeMap::from([("GITHUB_TOKEN".into(), "secret".into())]);
        let request = build_request(&api, &api.requests[1], &env).unwrap();
        assert_eq!(request.url, "https://api.github.com/users/octocat/repos?per_page=30&sort=updated");
        assert_eq!(request.headers["Authorization"], "Bearer secret");
        assert_eq!(
            build_request(&api, &api.requests[0], &BTreeMap::new()).unwrap_err(),
            "GITHUB_TOKEN is not set: add it to .env"
        );
    }
    #[test]
    fn query_auth_spaces_json_body_and_basic_auth() {
        let mut api = crate::boxes::new_api_box(&[], "Weather");
        api.auth = BoxAuth::Query { name: "appid".into(), env: "WEATHER_KEY".into() };
        let mut req = api.requests[0].clone();
        req.method = "POST".into();
        req.url = "https://x.org/find".into();
        req.query.push(crate::boxes::KeyValue { key: "q".into(), value: "a b".into(), arg: false });
        req.body = "{\"n\": 1}".into();
        let env = BTreeMap::from([("WEATHER_KEY".into(), "k".into())]);
        let request = build_request(&api, &req, &env).unwrap();
        assert_eq!(request.url, "https://x.org/find?q=a+b&appid=k");
        assert_eq!(request.body.as_deref(), Some("{\"n\": 1}"));
        req.body = "{bad".into();
        assert_eq!(build_request(&api, &req, &env).unwrap_err(), "The body isn't valid JSON.");
        req.body.clear();
        api.auth = BoxAuth::Basic { user_env: "X_USER".into(), pass_env: "X_PASSWORD".into() };
        let request = build_request(
            &api,
            &req,
            &BTreeMap::from([("X_USER".into(), "u".into()), ("X_PASSWORD".into(), "p".into())]),
        )
        .unwrap();
        assert_eq!(request.headers["Authorization"], "Basic dTpw");
    }
    #[test]
    fn block_hash_ignores_line_endings_and_uses_utf16_like_electron() {
        let text = "# forge:box x\nx = '😀'\n# forge:end x\n";
        assert_eq!(block_hash(text), block_hash(&text.replace('\n', "\r\n")));
        assert_eq!(block_hash(text).len(), 8);
        assert_ne!(block_hash(text), block_hash(&(text.to_owned() + "x")));
    }
}
